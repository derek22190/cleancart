function isZeroOrDietDrink(item: DrinkCatalogEntry): boolean {
  if ((item.nutrition.sugarsG100g ?? 0) > 0) return false;
  const zeroModifier =
    /\b(zero|sugar[\s-]*free|sugarfree|diet|ultra|lite|light|lyte|lo[\s-]*carb|low[\s-]*carb|unsweetened|sparkling\s+water|mineral\s+water|spring\s+water|seltzer|mountain\s+water)\b/i;
  if (zeroModifier.test(item.title)) return true;
  return item.keywords.some((k) => zeroModifier.test(k));
}

/**
 * Matches a user or screen-reader query against the comprehensive Beverage & Drink Encyclopedia.
 */
export function matchDrinkCatalog(query: string): DrinkCatalogEntry | null {
  const q = query.trim();
  if (!q) return null;
  const requiresZeroOrDiet =
    /\b(zero|sugar[\s-]*free|sugarfree|diet|ultra|lite|light|lyte|lo[\s-]*carb|low[\s-]*carb|unsweetened)\b/i.test(q);
  for (const item of DRINKS_CATALOG) {
    if (item.title.includes("/") || item.brand.includes("/")) continue;
    if (!hasValidCatalogProvenance(item.sourceUrl, item.verifiedAt)) continue;
    if (item.match.test(q)) {
      if (requiresZeroOrDiet && !isZeroOrDietDrink(item)) {
        continue;
      }
      if (!passesVariantGuard(q, item.title)) {
        continue;
      }
      return {
        ...item,
        sourceUrl: item.sourceUrl!,
        verifiedAt: item.verifiedAt!,
      };
    }
  }
  return null;
}

const IMAGE_STOP_TOKENS = new Set([
  "the", "and", "with", "for", "oz", "fl", "lb", "lbs", "ct", "count", "pack",
  "original", "classic", "natural", "flavored", "flavor",
]);

function distinctiveImageTokens(s: string): string[] {
  return s
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, " ")
    .split(" ")
    .filter((t) => t.length >= 3 && !IMAGE_STOP_TOKENS.has(t) && !/^\d+$/.test(t));
}

export function hasProductIdentityMatch(query: string, candidateName: string): boolean {
  if (!passesVariantGuard(query, candidateName)) return false;
  const qTokens = distinctiveImageTokens(query);
  const cTokens = distinctiveImageTokens(candidateName);
  if (!qTokens.length || !cTokens.length) return false;
  const tokenMatches = (qt: string) =>
    cTokens.some((ct) => ct === qt || ct === `${qt}s` || qt === `${ct}s`);
  if (!tokenMatches(qTokens[0])) return false;
  const matched = qTokens.filter(tokenMatches);
  if (qTokens.length <= 2) {
    return matched.length === qTokens.length;
  }
  return matched.length / qTokens.length >= 0.75;
}

